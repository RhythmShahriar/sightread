// SignalsDocPath is where go run ./detect/cmd/signalsdoc writes the
// signal reference, relative to the module's folder.
const SignalsDocPath = "docs/signals.md"

// SignalsDoc renders docs/signals.md from core.Catalog and the explain
// text: a table of every signal, then one section per ID (its heading is
// the anchor the wiki's Sightread-Signal-Reference page links to) with
// severity, confidence, ecosystems, when it fires, false alarms, how to
// review it and the incidents it would have caught.
func SignalsDoc() []byte {
	var b bytes.Buffer
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("# Sightread signal reference\n\n")
	w("Generated by `go run ./detect/cmd/signalsdoc` from the signal catalogue\n")
	w("(`core/catalog.go`) and the explain text (`detect/explain/<id>.yaml`).\n")
	w("Edit those, not this file: `TestSignalsDocCurrent` fails while it is stale.\n\n")
	w("Severity is the default before the context rules of PRD 12.2 raise or\n")
	w("lower it; `signals.severity` in the config overrides it. Confidence is\n")
	w("`confirmed` for an exact pattern and `likely` for a heuristic\n")
	w("(`--min-confidence confirmed` drops the likely ones from the verdict).\n")
	w("`rhythm-sightread explain <id>` prints a section in the terminal.\n\n")
	w("| ID | Severity | Confidence | Ecosystems | Title |\n|---|---|---|---|---|\n")
	for _, s := range core.Catalog {
		w("| [`%s`](#%s) | %s | %s | %s | %s |\n", s.ID, s.ID, s.Severity, s.Confidence, ecosystems(s.Ecosystems), s.Title)
	}
	for _, s := range core.Catalog {
		t := texts[s.ID]
		w("\n## %s\n\n", s.ID)
		w("**%s**\n\n", s.Title)
		sev := s.Severity.String()
		if s.Unignorable {
			sev += " (never ignored, allowed or lowered)"
		}
		w("- Severity: %s\n", sev)
		w("- Confidence: %s\n", s.Confidence)
		w("- Ecosystems: %s\n", ecosystems(s.Ecosystems))
		if s.Emitter == core.EmitPolicy {
			w("- Raised by: the allow list check, not a detector\n")
		}
		w("- Advice: %s\n", t.Advice)
		w("\n### Fires when\n\n%s\n", para(t.Why))
		w("\n### False alarms\n\n%s\n", para(t.FalseAlarms))
		w("\n### How to review\n\n")
		for i, step := range t.HowToReview {
			w("%d. %s\n", i+1, step)
		}
		w("\n### Incidents\n\n")
		if len(t.Incidents) == 0 {
			w("None recorded yet.\n")
		}
		for _, in := range t.Incidents {
			w("- **%s**: %s\n", in.Name, in.Line)
		}
	}
	return b.Bytes()
}

// ecosystems prints a signal's ecosystems: "all" for the four, else
// the list in catalogue order.
func ecosystems(ecos []core.Ecosystem) string {
	all := core.Ecosystems()
	if len(ecos) == len(all) && !slices.ContainsFunc(all, func(e core.Ecosystem) bool { return !slices.Contains(ecos, e) }) {
		return "all"
	}
	out := make([]string, len(ecos))
	for i, e := range ecos {
		out[i] = string(e)
	}
	return strings.Join(out, ", ")
}

// para folds the white space of a YAML block into one paragraph.
func para(s string) string { return strings.Join(strings.Fields(s), " ") }
