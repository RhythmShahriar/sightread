// Render writes docs/benchmark.md for r. corpus is the real-release block
// (markers included) kept from the previous page; see CorpusBlock.
func Render(r *Results, corpus string) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	w("# Sightread benchmark\n\n%s\n\n%s\n\n", Header, Framing)

	took := time.Duration(r.Seconds * float64(time.Second)).Round(time.Second)
	w("| | |\n|---|---|\n")
	w("| Run | %s, took %s |\n", r.Started.UTC().Format("2006-01-02 15:04 UTC"), took)
	w("| Binary | %s |\n", cell(orDash(r.Version)))
	w("| Machine | %s |\n", cell(orDash(r.Machine)))
	w("| Compared tools | %s |\n", cell(toolLine(r.Tools)))
	if r.Partial {
		w("| Scope | partial run (-only): the targets below are not claimed |\n")
	}
	w("\n")

	w("## 1.0 targets\n\n")
	notRun := r.NotRunTargets()
	switch {
	case r.Met():
		w("**Every target is met.**\n\n")
	case !r.Partial && len(r.Failed()) == 0 && len(notRun) > 0:
		var names []string
		for _, t := range notRun {
			names = append(names, t.Name+" ("+t.NotRun+")")
		}
		w("**Not every target was run, so not every target is met.** Nothing that ran failed. Not run on this machine: %s.\n\n",
			strings.Join(names, "; "))
	default:
		w("**Not every target is met.** The bench exits non-zero until they are.\n\n")
	}
	w("| Target | Result | Detail |\n|---|---|---|\n")
	for _, t := range r.Targets() {
		w("| %s | %s | %s |\n", t.Name, t.Result(), cell(t.Detail))
	}
	w("\n")

	w("%s\n", scenario.Scoreboard(outcomes(r)))
	renderMismatches(w, r)
	renderFalseAlarms(w, r)
	renderSafety(w, r)
	renderEnv(w, "## Environment scenarios", "Each runs the real binary against the registry, the probes or a misbehaving front and checks what it printed, its exit code and what it left behind.", r.Env)
	renderEnv(w, "## --soundcheck end to end (e15)", "Against the sealed Docker WordPress on 127.0.0.1:18907 with the Roadie stub. The applying case uses the real rhythm-soundcheck; every refusal must stop before any change, with the container's plugin and the host project byte-identical.", r.Staging)
	renderReproducibility(w, r)
	renderSpeed(w, r)
	renderTools(w, r)

	w("## Known gaps\n\nWhat this board does not cover:\n\n")
	for _, g := range KnownGaps {
		w("- %s\n", g)
	}
	w("\n%s", corpus)
	return b.String()
}

// outcomes rebuilds the scenario outcomes the scoreboard renders.
func outcomes(r *Results) []scenario.Outcome {
	out := make([]scenario.Outcome, 0, len(r.Scenarios))
	for _, s := range r.Scenarios {
		out = append(out, scenario.Outcome{
			Scenario:    scenario.Scenario{ID: s.ID, Kind: s.Kind, Title: s.Title, Pending: s.Pending},
			Status:      scenario.Status(s.Status),
			Present:     s.Present,
			Missing:     s.Missing,
			FalseAlarms: s.FalseAlarms,
			Forbidden:   s.Forbidden,
			GotVerdict:  s.Verdict,
		})
	}
	return out
}

func renderMismatches(w func(string, ...any), r *Results) {
	w("### Exit codes, verdicts and problems\n\n")
	n := 0
	for _, s := range r.Scenarios {
		m := s.Mismatch()
		if s.Problem != "" {
			m = append(m, s.Problem)
		}
		if len(m) == 0 {
			continue
		}
		if n == 0 {
			w("| Scenario | What differs |\n|---|---|\n")
		}
		n++
		w("| %s | %s |\n", s.ID, cell(strings.Join(m, "; ")))
	}
	if n == 0 {
		w("Every scenario gave the expected exit code, verdict and Not checked reasons.\n")
	}
	w("\n")
}

func renderFalseAlarms(w func(string, ...any), r *Results) {
	w("## False alarms\n\nFindings at or above each good scenario's gate (medium unless its entry says otherwise) that it is not allowed. An exact scenario (g15) counts any other finding at any severity and lists a required signal it did not report as missing.\n\n")
	w("| Scenario | Findings | Signals |\n|---|---|---|\n")
	for _, s := range r.Scenarios {
		if s.Kind != "good" {
			continue
		}
		list := append([]string(nil), s.FalseAlarms...)
		for _, m := range s.Missing {
			list = append(list, "missing:"+m)
		}
		w("| %s | %d | %s |\n", s.ID, len(s.FalseAlarms), cell(listOrDash(list)))
	}
	c := r.Control
	w("\nControl pass: every good scenario again %d times on a warm cache, %d runs, %d false alarms; outcome changed between rounds: %s.\n\n",
		c.Rounds, c.Runs, c.FalseAlarms, listOrNone(c.Unstable))
}

func renderSafety(w func(string, ...any), r *Results) {
	s := r.Safety
	w("## Safety\n\nEvery bad payload targets the canary: it would connect to 127.0.0.1:18905 and write a file under testbed/state/canary if it ever ran. HTTPS_PROXY and HTTP_PROXY point at the proxy guard on 127.0.0.1:23399, which closes every connection, so a forgotten base URL fails and is counted. HOME and the project fixtures are walked before and after every run. Fixtures carry fake keys built at run time; every output and report is searched for them in full. Sightread runs with a fake GITHUB_TOKEN and codeload answers on a second host name (localhost), so a token sent across the zipball redirect is counted.\n\n")
	w("| Counter | Count | Must be |\n|---|---|---|\n")
	w("| Canary connections | %d | 0 |\n", s.CanaryConnections)
	w("| Canary files | %d | 0 |\n", len(s.CanaryFiles))
	w("| Egress attempts | %d | 0 |\n", len(s.Egress))
	w("| Files written outside the work folders | %d | 0 |\n", len(s.OutsideWrites))
	w("| Fake keys printed or written unmasked | %d | 0 |\n", len(s.Unmasked))
	w("| Codeload requests carrying GITHUB_TOKEN | %d | 0 |\n\n", len(s.Forwarded))
	for _, list := range []struct {
		name  string
		items []string
	}{{"Canary files", s.CanaryFiles}, {"Egress attempts", s.Egress}, {"Outside writes", s.OutsideWrites}, {"Unmasked fake keys", s.Unmasked}, {"Credentials sent to codeload", s.Forwarded}} {
		if len(list.items) == 0 {
			continue
		}
		w("%s:\n\n", list.name)
		for _, it := range limit(list.items, 20) {
			w("- `%s`\n", strings.ReplaceAll(it, "`", "'"))
		}
		w("\n")
	}
}

func renderEnv(w func(string, ...any), title, intro string, rows []EnvResult) {
	w("%s\n\n%s\n\n", title, intro)
	if len(rows) == 0 {
		w("Not run in this benchmark.\n\n")
		return
	}
	w("| ID | Situation | Result | Notes |\n|---|---|---|---|\n")
	for _, e := range rows {
		res := e.Result
		if res == ResultFail {
			res = "**FAIL**"
		}
		notes := "-"
		if len(e.Notes) > 0 {
			notes = strings.Join(e.Notes, "; ")
		}
		w("| %s | %s | %s | %s |\n", e.ID, cell(e.Title), res, cell(notes))
	}
	w("\n")
}

func renderReproducibility(w func(string, ...any), r *Results) {
	agree, total := 0, 0
	for _, s := range r.Scenarios {
		total++
		if s.Reproducible() {
			agree++
		}
	}
	w("## Reproducibility\n\nCold and warm runs gave the same outcome for %d of %d scenarios. `make -C testbed reproduce` runs the whole benchmark twice and diffs the two results.json files outcome by outcome; the nightly workflow runs it on Linux.\n\n", agree, total)
}

func renderSpeed(w func(string, ...any), r *Results) {
	w("## Speed and memory\n\nWall time and peak RSS of the rhythm-sightread process (from its rusage), on the machine above. Cold is an empty cache, warm the second run on the same cache.\n\n")
	l := r.Large
	if l.Ran {
		w("p01-large (%d files, %.0f MB, not a scored scenario): cold %.2f s and %.0f MB, warm %.2f s and %.0f MB; target under %s warm and under %d MB.\n\n",
			l.Files, l.MB, l.Cold.Seconds, l.Cold.RSSMB, l.Warm.Seconds, l.Warm.RSSMB, LargeWarmLimit, LargeRSSLimitMB)
	} else {
		w("p01-large: not run (%s).\n\n", orDash(l.Note))
	}
	w("Full benchmark: %s; target under %s.\n\n", time.Duration(r.Seconds*float64(time.Second)).Round(time.Second), BenchLimit)
	w("| Scenario | Cold s | Warm s | Peak RSS MB |\n|---|---|---|---|\n")
	for _, s := range r.Scenarios {
		w("| %s | %.2f | %.2f | %.0f |\n", s.ID, s.Cold.Seconds, s.Warm.Seconds, max(s.Cold.RSSMB, s.Warm.RSSMB))
	}
	w("\n")
}

func renderTools(w func(string, ...any), r *Results) {
	w("## Compared tools\n\nOn the same fixture states. composer audit and npm audit point at the fixture registry, which publishes the same advisories OSV serves; they know only published advisories, so they miss a fresh malicious update by design, not by defect. GuardDog scans the npm tarballs offline. Soundcheck compares the Docker WordPress before and after each update, the stand-in for a visual-only safe update: a backdoor changes nothing visible.\n\n")
	if len(r.Tools) == 0 {
		w("No compared tool was run.\n\n")
		return
	}
	w("| Tool | Version | Sees |\n|---|---|---|\n")
	for _, t := range r.Tools {
		v := t.Version
		if t.NotRun != "" {
			v = "not run: " + t.NotRun
		}
		w("| %s | %s | %s |\n", t.Name, cell(orDash(v)), cell(t.Scope))
	}
	w("\n| Scenario | Sightread |")
	sep := "|---|---|"
	for _, t := range r.Tools {
		w(" %s |", t.Name)
		sep += "---|"
	}
	w("\n%s\n", sep)
	for _, s := range r.Scenarios {
		if s.Kind != "bad" && s.Kind != "good" {
			continue
		}
		w("| %s | %s |", s.ID, sightreadLabel(s))
		for _, t := range r.Tools {
			label := s.Tools[t.Name]
			if t.NotRun != "" || label == "" {
				label = ToolNotRun
			}
			if label == ToolCaught {
				label = "**caught**"
			}
			w(" %s |", label)
		}
		w("\n")
	}
	w("\n")
}

// sightreadLabel is Sightread's cell in the compared tools table.
func sightreadLabel(s ScenarioResult) string {
	switch s.Status {
	case "caught":
		return "**caught**"
	case "found-as-something-else":
		return "found as something else"
	case "false-alarm":
		return "false alarm"
	}
	return s.Status
}

// toolLine names each compared tool with its version.
func toolLine(tools []Tool) string {
	if len(tools) == 0 {
		return "none"
	}
	parts := make([]string, 0, len(tools))
	for _, t := range tools {
		if t.NotRun != "" {
			parts = append(parts, t.Name+" not run ("+t.NotRun+")")
		} else {
			parts = append(parts, strings.TrimSpace(t.Name+" "+t.Version))
		}
	}
	return strings.Join(parts, "; ")
}

// cell makes text safe inside a Markdown table cell.
func cell(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	return strings.ReplaceAll(s, "\n", " ")
}

// listOrDash joins ss sorted, or a dash.
func listOrDash(ss []string) string {
	if len(ss) == 0 {
		return "-"
	}
	c := append([]string(nil), ss...)
	sort.Strings(c)
	return strings.Join(c, ", ")
}

// limit keeps the first n items and says how many more there were.
func limit(ss []string, n int) []string {
	if len(ss) <= n {
		return ss
	}
	return append(append([]string(nil), ss[:n]...), fmt.Sprintf("... and %d more in results.json", len(ss)-n))
}
